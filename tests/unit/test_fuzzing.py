"""Generated input for each function that reads what someone else wrote (threat T40).

The other tests try the inputs someone thought of. These try the ones nobody
did, generated by Hypothesis, and check what must hold for all of them:

- the file extractors return text or refuse the file, and never fail any
  other way, for real company files damaged at random;
- a question is cleaned to one line, or refused, and cleaning it twice
  changes nothing;
- whatever a question or a document says, the prompt has exactly its
  blocks, and each block holds exactly what was put in it;
- whatever an answer says, no link it keeps goes anywhere but its sources,
  and a citation is only ever to a source the answer was given;
- whatever a title says, the UI shows it as exactly itself;
- a filter is either valid or refused, whatever shape it comes in.

Runs are derandomized (tests/conftest.py), so a failure is the same on every
run until the code changes.

Two real faults were found writing these. A damaged Word file could make the
zip reader raise NotImplementedError, a 500. And the PDF reader's warnings
quote the bytes it tripped over, so a damaged PDF put document text in the
application log; the last test here is for that.
"""

