DOCUMENTS = Path(__file__).resolve().parents[2] / "data" / "acmecorp" / "documents"
PDFS = [p.read_bytes() for p in sorted(DOCUMENTS.rglob("*.pdf"))]
WORD = [p.read_bytes() for p in sorted(DOCUMENTS.rglob("*.docx"))]
TEXTS = [p.read_bytes() for p in sorted(DOCUMENTS.rglob("*.txt"))]

# Damage done to a file: bytes overwritten, put in or taken out, at random places.
Damage = list[tuple[int, int, bytes]]
DAMAGE = st.lists(
    st.tuples(st.integers(0, 2), st.integers(0, 10**7), st.binary(min_size=1, max_size=12)),
    min_size=1,
    max_size=12,
)


def damaged(data: bytes, damage: Damage) -> bytes:
    out = bytearray(data)
    for kind, where, value in damage:
        at = where % (len(out) + 1)
        if kind == 0:
            out[at : at + len(value)] = value
        elif kind == 1:
            out[at:at] = value
        else:
            del out[at : at + len(value) * 4]
    return bytes(out)


def text_or_refused(extract: Callable[[bytes], str], data: bytes) -> None:
    with contextlib.suppress(InvalidInputError):
        assert isinstance(extract(data), str)


# --- files ------------------------------------------------------------------------------


@given(st.sampled_from(range(len(PDFS))), DAMAGE)
def test_a_damaged_pdf_gives_text_or_is_refused(which: int, damage: Damage) -> None:
    text_or_refused(extract_pdf, damaged(PDFS[which], damage))


@given(st.sampled_from(range(len(WORD))), DAMAGE)
def test_a_damaged_word_file_gives_text_or_is_refused(which: int, damage: Damage) -> None:
    text_or_refused(extract_docx, damaged(WORD[which], damage))


@given(st.one_of(st.binary(max_size=2000), st.sampled_from(TEXTS)), DAMAGE)
def test_any_bytes_as_a_text_file_give_text_or_are_refused(data: bytes, damage: Damage) -> None:
    text_or_refused(extract_txt, damaged(data, damage))


def test_the_zip_versions_the_reader_does_not_support_are_refused_not_a_500() -> None:
    # The case the fuzzing found: the version a member says it needs, made up.
    archive = bytearray(WORD[0])
    central = archive.rfind(b"PK\x01\x02")
    archive[central + 6 : central + 8] = (215).to_bytes(2, "little")

    with pytest.raises(InvalidInputError, match="not a Word document"):
        extract_docx(bytes(archive))


# --- questions --------------------------------------------------------------------------

SETTINGS = Settings(_env_file=None, jwt_secret_key=SecretStr("fuzzing-" + "k" * 40))


@given(st.text(max_size=SETTINGS.max_question_characters + 50))
def test_a_question_is_cleaned_to_one_line_or_refused(raw: str) -> None:
    try:
        text = clean_question(raw, SETTINGS)
    except InvalidInputError:
        return

    assert text == text.strip()
    assert not re.search(r"\s\s|[\n\r\t]", text)
    assert 0 < len(text) <= SETTINGS.max_question_characters
    assert any(character.isalnum() for character in text)
    assert clean_question(text, SETTINGS) == text


# --- the prompt -------------------------------------------------------------------------

BLOCK = re.compile(
    r'<source id="(S\d+)" document="([^"]*)" version="(\d+)">\n(.*?)\n</source>', re.DOTALL
)
# Text made of the prompt's own markup, which characters drawn one at a time
# would almost never spell.
MARKUP = st.lists(
    st.sampled_from(
        [
            *("<source", ">", "</source>", "<question>", "</question>", 'id="S1"', '"', "'"),
            *("&", "&amp;", "&lt;", "&quot;", "\n", " ", "S2", "text"),
        ]
    ),
    max_size=20,
).map("".join)
ANY_TEXT = st.one_of(st.text(max_size=200), MARKUP)


def context_of(texts: list[tuple[str, str]]) -> Context:
    sources = tuple(
        Source(f"S{n}", n, UUID(int=n), title, 1, (n,), text, 0.5)
        for n, (title, text) in enumerate(texts, 1)
    )
    return Context(user_id=1, sources=sources, left_out=0)


@given(ANY_TEXT.filter(str.strip), st.lists(st.tuples(ANY_TEXT, ANY_TEXT), min_size=1, max_size=4))
def test_whatever_the_text_says_the_prompt_has_exactly_its_blocks(
    question: str, texts: list[tuple[str, str]]
) -> None:
    context = context_of(texts)
    prompt = build_prompt(ProcessedQuestion(question, np.zeros(4, np.float32), 1), context)

    sources, _, asked = prompt.user.rpartition("\n\n<question>\n")
    found = BLOCK.findall(sources)
    assert [(label, html.unescape(title)) for label, title, _, _ in found] == [
        (s.label, s.document_title) for s in context.sources
    ]
    assert [html.unescape(text) for *_, text in found] == [s.text for s in context.sources]
    assert prompt.user.count("<source ") == len(context.sources)
    assert prompt.user.count("</source>") == len(context.sources)
    assert asked.endswith("\n</question>")
    assert html.unescape(asked.removesuffix("\n</question>")) == question
    assert "<question>" not in asked and "</question>" not in asked[: -len("\n</question>")]


# --- answers ----------------------------------------------------------------------------

OWN = "https://intranet.acme.example/leave"
# Pieces of answers, links and the ways they can be written: put together at
# random, they make links of every shape, broken ones included.
PIECES = st.sampled_from(
    [
        "Leave is 25 days ",
        "[S1]",
        "[S2]",
        "[S9]",
        "(",
        ")",
        "[",
        "]",
        "![",
        "!",
        " ",
        "\n",
        "see ",
        OWN,
        f"[the policy]({OWN})",
        f"![chart]({OWN})",
        "https://evil.example/c?q=",
        "HTTPS://EVIL.EXAMPLE/c?q=",
        "http://evil.example",
        "//evil.example/pixel.png",
        "www.evil.example/x",
        "mailto:leak@evil.example",
        "ftp://evil.example/",
        "<https://evil.example>",
        "`https://evil.example`",
        f"{OWN}.evil.example/",
        "](https://evil.example/a)",
        '"https://evil.example"',
        "salary 68,000",
    ]
)
ANSWERS = st.lists(PIECES, max_size=25).map("".join)


def answer_context() -> Context:
    return context_of([("Leave Policy", f"Leave is 25 days. Details: {OWN} for all staff.")])


# Bare text a renderer turns into a link: GFM's autolinks, which Streamlit's
# Markdown has. Text such as "//evil.example" on its own is not one.
AUTOLINKED = re.compile(r"(?:https?://|ftp://|www\.|mailto:)[^\s<]*evil\.example", re.IGNORECASE)
LINK_TARGET = re.compile(r'(?:href|src)="([^"]*)"')


@given(ANSWERS)
def test_whatever_an_answer_says_no_link_it_keeps_goes_outside_its_sources(answer: str) -> None:
    kept = remove_foreign_links(answer, answer_context())

    # Every link a Markdown renderer would make of it, and every bare address
    # it would turn into one, goes to the answer's own source or nowhere.
    targets = LINK_TARGET.findall(MARKDOWN.render(kept.text))
    assert [t for t in targets if html.unescape(t) != OWN] == []
    assert AUTOLINKED.search(kept.text) is None
    assert "![" not in kept.text
    # Done once, it is done: a second pass finds nothing more to take out.
    assert remove_foreign_links(kept.text, answer_context()).removed == 0


@given(ANSWERS)
def test_whatever_an_answer_says_it_cites_only_its_own_sources(answer: str) -> None:
    context = answer_context()

    cited = resolve_citations(answer, context)

    assert {source.label for source in cited.sources} <= {"S1"}
    assert cited.unknown >= 0
    assert not re.search(r"\[S[02-9]\]", cited.text)


# --- what the UI shows ------------------------------------------------------------------

MARKDOWN = MarkdownIt("commonmark", {"html": True}).enable(["table", "strikethrough"])
PUNCTUATION = st.text(
    alphabet=st.sampled_from(list("!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~ \nab1:")), max_size=80
)


@given(st.one_of(st.text(max_size=120), PUNCTUATION))
def test_whatever_a_title_says_the_ui_shows_it_as_exactly_itself(text: str) -> None:
    flat = " ".join(text.split())
    out = MARKDOWN.render(literal(text)).strip()

    if not flat:
        assert out == ""
        return
    assert out.startswith("<p>") and out.endswith("</p>")
    assert out.count("<") == 2
    # CommonMark has a renderer replace NUL with U+FFFD, so that is shown for it.
    assert html.unescape(out[3:-4]) == flat.replace("\x00", "\ufffd")


# --- filters ----------------------------------------------------------------------------

JSON = st.recursive(
    st.none() | st.booleans() | st.integers() | st.floats() | st.text(max_size=20),
    lambda inner: (
        st.lists(inner, max_size=4) | st.dictionaries(st.text(max_size=12), inner, max_size=4)
    ),
    max_leaves=12,
)
FILTER_SHAPED = st.dictionaries(
    st.sampled_from(["departments", "classifications", "document_ids", "user", "x"]),
    # IDs around the database's largest, which small numbers never reach.
    st.one_of(
        JSON,
        st.lists(st.one_of(st.integers(-5, 1000), st.integers(2**63 - 2, 2**70)), max_size=4),
    ),
    max_size=3,
)


IDS = st.lists(st.one_of(st.integers(-5, 1000), st.integers(2**63 - 2, 2**70)), min_size=1)
# Otherwise valid, so an ID is the only thing that can be wrong with it.
ONLY_IDS = st.fixed_dictionaries({"document_ids": IDS})


@given(st.one_of(JSON, FILTER_SHAPED, ONLY_IDS))
def test_a_filter_is_valid_or_refused_whatever_shape_it_comes_in(value: object) -> None:
    try:
        filters = SearchFilters.model_validate(value)
    except ValidationError:
        return
    assert isinstance(filters, SearchFilters)
    for document_id in filters.document_ids or ():
        assert isinstance(document_id, UUID)


# --- what the parsers log ---------------------------------------------------------------


def test_a_damaged_pdf_puts_none_of_its_text_in_the_log(capsys: pytest.CaptureFixture[str]) -> None:
    # Found by the fuzzing above: the PDF reader's warnings quote the file.
    words = "Salary band for E-2291 is 68,000 to 92,000 per year."
    pdf = make_pdf([words])
    assert b"68,000" in pdf
    # Damage that is the same on every run, not a secret.
    rng = random.Random(84)  # noqa: S311
    with logging_restored():
        configure_logging("DEBUG")
        for _ in range(300):
            data = bytearray(pdf)
            for _ in range(3):
                data[rng.randrange(len(data))] = rng.randrange(256)
            text_or_refused(extract_pdf, bytes(data))
        log = capsys.readouterr().out

    assert "68,000" not in log
    assert "E-2291" not in log
    assert "Salary band" not in log
